import { useEffect, useState } from "react";
import { getSummary } from "../services/api";

export default function AutoInsights({ dataset, onAsk }) {
  const [data, setData] = useState(null);
  const [loading, setLoading] = useState(true);
  const [error, setError] = useState(null);

  async function load(refresh = false, isCancelled = () => false) {
    setLoading(true);
    setError(null);
    try {
      const d = await getSummary(dataset.id, refresh);
      if (!isCancelled()) setData(d);
    } catch (e) {
      if (!isCancelled()) setError(e.response?.data?.error || e.message);
    } finally {
      if (!isCancelled()) setLoading(false);
    }
  }

  useEffect(() => {
    let cancelled = false;
    setData(null);
    load(false, () => cancelled);
    return () => { cancelled = true; };
  }, [dataset.id]);

  if (loading) {
    return (
      <div className="page">
        <div className="ai-hero"><span className="ai-badge">✦ AI summary</span><h2>Reading your dataset…</h2></div>
        <div className="skeleton" style={{ width: "92%" }} />
        <div className="skeleton" style={{ width: "78%" }} />
        <div className="skeleton" style={{ width: "85%" }} />
        <div className="skeleton" style={{ width: "64%" }} />
      </div>
    );
  }

  if (error) {
    return (
      <div className="page">
        <div className="error-banner">{error}</div>
        <button className="btn-ghost" style={{ marginTop: 14 }} onClick={() => load(true)}>Try again</button>
      </div>
    );
  }

  if (!data) return null;

  return (
    <div className="page">
      <div className="ai-hero">
        <span className="ai-badge">✦ AI summary</span>
        <h2>{data.headline}</h2>
        <p className="muted">Generated by Gemini from your dataset's statistics · {new Date(data.generatedAt).toLocaleTimeString([], { hour: "2-digit", minute: "2-digit" })}</p>
      </div>

      <h2>Key findings</h2>
      <ol className="findings">
        {data.findings.map((f, i) => <li key={i}><span>{i + 1}</span>{f}</li>)}
      </ol>

      {data.watchouts.length > 0 && (
        <>
          <h2>Watch-outs</h2>
          <ul className="watchouts">
            {data.watchouts.map((w, i) => <li key={i}>{w}</li>)}
          </ul>
        </>
      )}

      {data.questions.length > 0 && (
        <>
          <h2>Ask next</h2>
          <div className="chips left">
            {data.questions.map((q) => <button key={q} className="chip" onClick={() => onAsk(q)}>{q} →</button>)}
          </div>
        </>
      )}

      <button className="btn-ghost" style={{ marginTop: 26 }} onClick={() => load(true)}>↻ Regenerate summary</button>
    </div>
  );
}